"""Integration: one canonical formatting path for engineering values.

A value is stored with the same text whichever way it enters the library: typed by hand
(``create_part`` with "4k7"), generated by a series (``upsert_parts`` with the float 4700
or with ``domain.units.format_quantity`` text), or formatted directly through
``db.values`` – because ``db.values`` delegates to ``domain.units``.
"""
from __future__ import annotations

import math
import random

import pytest

from partforge.db import parts
from partforge.db.models import FieldDef
from partforge.db.values import (
    canonical_unit,
    format_field_quantity,
    format_rkm_value,
    normalize_cell,
    numeric_value,
    parse_field_quantity,
    render_template,
    units_compatible,
)
from partforge.domain import eseries
from partforge.domain.units import (
    NO_PREFIX_UNITS,
    exact_digits,
    format_power,
    format_quantity,
    format_rkm,
    normalize_unit,
    parse_quantity,
)
from partforge.workspace import Workspace


def _field(unit: str) -> FieldDef:
    return FieldDef(column="X", label="X", kind="quantity", unit=unit)


def _decades(series: str, lo_exp: int, hi_exp: int) -> list[float]:
    return [m * 10**e for e in range(lo_exp, hi_exp + 1) for m in eseries.SERIES[series]]


@pytest.mark.parametrize(
    ("unit", "values"),
    [
        ("Ω", _decades("E96", 0, 6)),
        ("F", _decades("E24", -12, -4)),
        ("H", _decades("E12", -9, -3)),
        ("Hz", [32768.0, 14_318_180.0, 8e6, 1.8432e6, 25e6, 100e3]),
        ("V", [1.8, 3.3, 5.0, 6.3, 16.0, 25.0, 50.0, 100.0, 630.0]),
        ("W", [0.0625, 0.05, 0.1, 0.125, 0.25, 0.5, 1.0, 2.5]),
        ("%", [0.1, 0.5, 1.0, 2.0, 5.0, 10.0, 20.0]),
        ("ppm", [10.0, 20.0, 30.0, 50.0]),
        ("ppm/K", [25.0, 50.0, 100.0, -750.0]),
        ("K", [0.5, 77.0, 300.0, 1000.0, 6500.0, 1.2e6]),  # kelvin: "K" is the unit, never kilo
        ("°C", [-55.0, -40.0, 0.0, 25.0, 85.0, 155.0, 1250.0]),
        ("mm", [0.55, 1.75, 2.54, 12.5, 1000.0, 0.0001]),
        ("in", [0.1, 1.5, 12.0, 2000.0]),
        ("T", [0.001, 0.5, 1.5, 5.0, 3000.0]),  # units unknown to domain.units (user-defined fields)
        ("lm", [0.25, 120.0, 1500.0]),
    ],
)
def test_all_entry_paths_give_identical_text(unit: str, values: list[float]) -> None:
    field = _field(unit)
    for value in values:
        canonical = format_field_quantity(value, unit, plus_minus=unit in ("%", "ppm", "ppm/K"))
        assert normalize_cell(field, value).value == canonical, value  # float from a series/spreadsheet
        assert normalize_cell(field, canonical).value == canonical, value  # idempotent
        units_text = format_quantity(value, unit, digits=None)  # series assistant text
        assert normalize_cell(field, units_text).value == canonical, (value, units_text)
        rkm = format_rkm(value, unit, upper=False, digits=None)
        if unit in ("Ω", "F", "H", "V") or unit in NO_PREFIX_UNITS:  # "4k7", "100n", "6V3", "6500K" are inputs too
            assert normalize_cell(field, rkm).value == canonical, (value, rkm)
        assert format_rkm_value(value, unit) == rkm
        q = parse_field_quantity(canonical, unit)
        assert q is not None and math.isclose(q.value, value, rel_tol=1e-9)
        assert math.isclose(numeric_value(canonical, unit) or 0.0, value, rel_tol=1e-9)


def test_manual_and_series_paths_store_identical_rows(workspace: Workspace) -> None:
    base = {"Manufacturer": "Vishay", "Technology": "Dickschicht", "Size": "0603", "Library Ref": "Resistor",
            "Footprint Ref": "RESC1608X50N"}
    resistances = [v for v in _decades("E24", 0, 5) if v <= 1e6]
    manual: dict[float, dict] = {}
    for i, value in enumerate(resistances):
        text = format_rkm(value, "Ω", upper=bool(i % 2), digits=None)  # "4k7" / "4K7" as typed by hand
        pn = f"MAN-{i:03d}"
        manual[value] = parts.create_part("Resistors", {**base, "Part Number": pn, "Resistance": text,
                                                        "Tolerance": "1 %", "Power": "1/10W", "TCR": "±100 ppm"})
    series_rows = [{**base, "Part Number": f"SER-{i:03d}", "Resistance": value, "Tolerance": 1.0, "Power": 0.1,
                    "TCR": "±100ppm/K"} for i, value in enumerate(resistances)]
    result = parts.upsert_parts("Resistors", series_rows)
    assert len(result.created) == len(resistances) and not result.errors and not result.warnings
    for i, value in enumerate(resistances):
        series = parts.get_part("Resistors", f"SER-{i:03d}")
        assert series is not None
        for column in ("Resistance", "Tolerance", "Power", "TCR", "Value", "Comment", "Description"):
            assert manual[value][column] == series[column], (value, column)
        assert series["Resistance"] == format_field_quantity(value, "Ω")
        assert series["Comment"] == format_rkm_value(value, "Ω")
        assert series["Tolerance"] == "±1%" and series["Power"] == "0.1W" and series["TCR"] == "±100ppm/K"


def test_ppm_and_ppm_per_kelvin_are_distinct_but_interchangeable() -> None:
    assert normalize_unit("ppm") == "ppm" and normalize_unit("ppm/°C") == "ppm/K"
    assert parse_quantity("±20 ppm").unit == "ppm"  # type: ignore[union-attr]
    assert parse_quantity("100ppm/K").unit == "ppm/K"  # type: ignore[union-attr]
    assert canonical_unit("ppm") == "ppm" and units_compatible("ppm", "ppm/K") and units_compatible("ppm/K", "ppm")
    assert not units_compatible("ppm", "%")
    tolerance, tcr = _field("ppm"), _field("ppm/K")
    assert normalize_cell(tolerance, "20").value == "±20ppm"  # crystal frequency tolerance: a ratio
    assert normalize_cell(tolerance, "±20ppm/K").value == "±20ppm"
    assert normalize_cell(tcr, "±100ppm").value == "±100ppm/K"  # TCR typed without "/K"
    assert normalize_cell(tcr, "-750").value == "-750ppm/K"
    assert normalize_cell(_field(""), "20ppm").value == "±20ppm"  # no field unit: the typed unit counts
    assert format_quantity(20, "ppm") == "20ppm" and format_quantity(20, "ppm/K") == "20ppm/K"


def test_house_rules_of_the_canonical_formatter() -> None:
    assert format_quantity(0.25, "W") == "0.25W" and format_quantity(0.0625, "W") == "62.5mW"
    assert format_power(0.25) == "0.25W" and format_power(0.0625, style="fraction") == "1/16W"
    assert format_quantity(1, "%", plus_minus=True) == "±1%" and format_quantity(-0.5, "%", plus_minus=True) == "-0.5%"
    assert format_quantity(0, "%", plus_minus=True) == "±0%"
    assert {"%", "ppm", "ppm/K", "°C", "mm", "K", "in"} <= NO_PREFIX_UNITS
    assert format_quantity(1e-7, "%") == "0.0000001%"  # no precision lost without prefix
    assert format_quantity(14_318_180, "Hz", digits=None) == "14.31818MHz"
    assert format_quantity(14_318_180, "Hz") == "14.3182MHz"  # display default: 6 digits
    assert exact_digits(4700) == 3 and exact_digits(14.31818e6) == 7 and exact_digits(math.pi) == 9
    assert format_rkm(6.3, "V") == "6V3" and format_rkm(1e-7, "F") == "100n" and format_rkm(2.2e-6, "F") == "2u2"
    assert format_rkm(4700) == "4K7" and format_rkm(4700, upper=False) == "4k7" and format_rkm(-0.47) == "-R47"
    assert format_rkm(1.02e-7) == "R000000102"  # tiny values no longer crash
    assert parse_quantity("1/16W").unit == "W"  # type: ignore[union-attr]


@pytest.mark.parametrize("text", ["1e999", "-1e999", "inf", "nan"])
def test_non_finite_input_is_a_warning_not_a_crash(text: str) -> None:
    assert parse_quantity(text) is None and parse_quantity(float(text)) is None
    result = normalize_cell(_field("Ω"), text)
    assert result.value == text and result.warning and result.error is None
    assert numeric_value(text, "Ω") is None


def test_templates_use_the_same_formatter() -> None:
    fields = {"Resistance": _field("Ω"), "Capacitance": _field("F"), "Voltage": _field("V")}
    values = {"Resistance": "4.7kΩ", "Capacitance": "100nF", "Voltage": "6.3V"}
    assert render_template("{Resistance:rkm} {Capacitance:rkm} {Voltage:rkm}", values, fields) == "4k7 100n 6V3"
    assert render_template("{Resistance:si} {Resistance:nounit}", {"Resistance": "4K7"}, fields) == "4.7kΩ 4.7k"
    assert render_template("{Resistance:nounit}", {"Resistance": "4K7"}, fields) == format_quantity(4700, "", digits=None)


_FUZZ_UNITS = ["Ω", "F", "H", "V", "A", "W", "Hz", "%", "ppm", "ppm/K", "°C", "°", "mm", "nm", "cd", "C", "s", "dB",
               "V/µs", "mil", "K", "", "lm", "in", "T", "Pa"]


def _fuzz_values(seed: int, count: int) -> list[float]:
    rng = random.Random(seed)
    fixed = [0.0, 1e-15, 1.5e-12, 4.7e-9, 2.2e-6, 1e-3, 0.0625, 0.099999, 0.1, 0.5, 0.999999, 1.0, 1.0000001, 4.7, 6.3,
             10.0, 99.99995, 100.0, 999.9996, 1000.0, 4700.0, 32768.0, 14_318_180.0, 1e9, 1e13, -55.0, -0.47, -750.0]
    return fixed + [rng.uniform(-1e6, 1e6) * 10 ** rng.randint(-12, 6) for _ in range(count)]


@pytest.mark.parametrize("unit", _FUZZ_UNITS)
def test_stored_quantities_never_change_when_normalised_again(unit: str) -> None:
    """Form saves, imports, bulk updates and re-validation normalise stored text again: the
    value must stay the same (regression: "6500K" in a kelvin field became 6.5 MK)."""
    field = _field(unit)
    for value in _fuzz_values(len(unit) * 7 + 1, 150):
        first = normalize_cell(field, value)  # (plain numbers for F/H get a "prefix?" hint – the value counts)
        assert first.value is not None and (first.warning is None or unit in ("F", "H")), (value, first)
        again = normalize_cell(field, first.value)
        assert again.value == first.value and again.warning is None, (value, first.value, again)
        number = numeric_value(first.value, unit or None)
        assert number is not None and math.isclose(number, value, rel_tol=1e-6, abs_tol=1e-30), (value, first.value)


@pytest.mark.parametrize("unit", ["V", "°C", "A", "Hz", "%", "K", "mm", "Ω", "T"])
def test_stored_ranges_never_change_when_normalised_again(unit: str) -> None:
    field = FieldDef(column="R", label="R", kind="range", unit=unit)
    rng = random.Random(unit)
    for _ in range(120):
        lo = rng.uniform(-100, 100) * 10 ** rng.randint(-3, 3)
        hi = lo + abs(rng.uniform(0, 100)) * 10 ** rng.randint(-3, 3)
        for text in (f"{lo} … {hi}", f"{lo} to {hi}", f"{lo}...{hi}"):
            first = normalize_cell(field, text)
            again = normalize_cell(field, first.value)
            assert first.warning is None and again.value == first.value and again.warning is None, (text, first, again)
    if unit in NO_PREFIX_UNITS:
        assert normalize_cell(field, "233 … 398").value == f"233{unit} … 398{unit}"


def test_kelvin_fields_read_k_as_unit_but_resistances_as_kilo() -> None:
    kelvin, ohm = _field("K"), _field("Ω")
    assert normalize_cell(kelvin, "6500").value == "6500K" and normalize_cell(kelvin, "6500K").value == "6500K"
    assert normalize_cell(kelvin, "6.5kK").value == "6500K" and parse_quantity("300K", "K") == parse_quantity(300, "K")
    assert normalize_cell(ohm, "10K").value == "10kΩ" and normalize_cell(ohm, "4K7").value == "4.7kΩ"
    assert parse_quantity("10K") is not None and parse_quantity("10K").value == 10_000  # type: ignore[union-attr]
    assert parse_quantity("5T", "T").value == 5 and parse_quantity("5mT", "T").value == 0.005  # type: ignore[union-attr]


def test_lower_case_k_in_kelvin_fields_is_the_unit() -> None:
    """Regression: "6500k" in a colour-temperature field became 6.5 MK (kilo-kelvin)."""
    kelvin, ohm, plain = _field("K"), _field("Ω"), _field("")
    assert normalize_cell(kelvin, "6500k").value == "6500K" and normalize_cell(kelvin, "6500 k").value == "6500K"
    kelvin_range = FieldDef(column="CCT", label="Farbtemperatur", kind="range", unit="K")
    assert normalize_cell(kelvin_range, "2700k … 6500k").value == "2700K … 6500K"
    assert parse_quantity("6500k", "K").value == 6500 and numeric_value("6500k", "K") == 6500  # type: ignore[union-attr]
    assert normalize_cell(kelvin, "6.5kK").value == "6500K" and normalize_cell(kelvin, "6k5").value == "6500K"  # explicit kilo
    # only kelvin fields: "k" stays kilo everywhere else
    assert normalize_cell(ohm, "10k").value == "10kΩ" and parse_quantity("10k").value == 10_000  # type: ignore[union-attr]
    assert parse_quantity("10k", "Hz").value == 10_000 and normalize_cell(plain, "10k").value == "10k"  # type: ignore[union-attr]
    assert normalize_cell(kelvin, normalize_cell(kelvin, "6500k").value).value == "6500K"  # stable when normalised again


def test_rkm_codes_of_units_without_prefix_keep_the_decimal_point() -> None:
    assert format_rkm(0.5, "%") == "0.5%" and format_rkm(12.5, "°C") == "12.5°C" and format_rkm(6500, "K") == "6500K"
    assert format_rkm(1e-7, "%", digits=None) == "0.0000001%" and format_rkm(-0.5, "%") == "-0.5%"
    assert format_rkm(1.5, "Hz") == "1.5Hz" and format_rkm(290, "V/µs") == "290V/µs" and format_rkm(10, "Hz") == "10Hz"
    assert format_rkm(32768, "Hz", upper=False, digits=None) == "32k768"  # prefixed: the letter marks the decimal point
    assert format_rkm(6.3, "V") == "6V3" and format_rkm(4.7, "") == "4.7" and format_rkm(4.7) == "4R7"
    fields = {"Tolerance": _field("%"), "Temp": _field("°C")}
    assert render_template("{Tolerance:rkm} {Temp:rkm}", {"Tolerance": "±0.5%", "Temp": "12.5°C"}, fields) == "0.5% 12.5°C"
    for text in ("0.5%", "12.5°C", "6500K", "1.5Hz"):
        assert parse_quantity(text) is not None, text


def test_smart_fill_accepts_ppm_for_a_tcr_field(workspace: Workspace) -> None:
    filled = parts.smart_fill("Resistors", "10k 1% 0603 0.1W ±100ppm")
    assert filled["values"].get("TCR") == "±100ppm/K" and filled["unmatched"] == []
    crystal = parts.smart_fill("Oscillators", "32.768kHz ±20ppm/K 12.5pF")
    assert crystal["values"].get("Frequency Tolerance") == "±20ppm" and crystal["unmatched"] == []
    exact = parts.smart_fill("Oscillators", "±20ppm 32.768kHz")  # a crystal's tolerance in ppm: exact unit
    assert exact["values"] == {"Frequency Tolerance": "±20ppm", "Frequency": "32.768kHz"}


def test_smart_fill_prefers_the_field_with_the_exact_unit(workspace: Workspace) -> None:
    """ppm and ppm/K accept each other, but a field with exactly the typed unit wins over an
    earlier field that only accepts it."""
    from partforge.db import categories
    from partforge.db.models import FieldDef

    categories.add_field("Oscillators", FieldDef(column="Temp Coefficient", label="TK", kind="quantity", unit="ppm/K"))
    categories.reorder_fields("Oscillators", ["Part Number", "Temp Coefficient"])  # now before the ppm fields
    both = parts.smart_fill("Oscillators", "±20ppm ±50ppm/K")
    assert both["values"] == {"Frequency Tolerance": "±20ppm", "Temp Coefficient": "±50ppm/K"}
    second = parts.smart_fill("Oscillators", "±10ppm ±30ppm ±5ppm")  # tolerance, stability, then the ppm/K field
    assert second["values"] == {"Frequency Tolerance": "±10ppm", "Frequency Stability": "±30ppm",
                                "Temp Coefficient": "±5ppm/K"}
    assert second["unmatched"] == []
